#pragma once

#include <cstddef>
#include <chrono>
#include <filesystem>
#include <deque>
#include <mutex>
#include <optional>
#include <string>
#include <string_view>
#include <unordered_map>
#include <unordered_set>
#include <vector>

#include "harness/tool.h"

namespace harness {

enum class PermissionDecision { Deny, Ask, Allow };

struct PermissionCheckResult {
  PermissionDecision decision = PermissionDecision::Deny;
  std::string authorization_resource;
  std::string execution_resource;

  friend bool operator==(const PermissionCheckResult& result,
                         PermissionDecision decision) {
    return result.decision == decision;
  }
};

struct PermissionRequest {
  // Generated by the trusted execution layer and never reused within a session.
  std::string invocation_id;
  std::string tool_name;
  PermissionScope scope;
  std::string resource;
};

struct PermissionRule {
  std::string tool_pattern;
  PermissionScope scope;
  std::string resource_pattern;
  PermissionDecision decision = PermissionDecision::Deny;
};

class PermissionManager final {
 public:
  explicit PermissionManager(std::filesystem::path project_root);

  void AddRule(PermissionRule rule);
  void ClearRules();

  [[nodiscard]] PermissionCheckResult Check(const PermissionRequest& request);
  [[nodiscard]] PermissionCheckResult GrantOnce(const PermissionRequest& request);
  [[nodiscard]] PermissionCheckResult GrantSession(const PermissionRequest& request);
  void DenyOnce(const PermissionRequest& request);
  void DenySession(const PermissionRequest& request);
  void Cancel(std::string_view invocation_id);
  void ClearSession();

  [[nodiscard]] std::size_t RuleCount() const;

 private:
  struct RequestKey {
    std::string invocation_id;
    std::string tool_name;
    PermissionScope scope;
    std::string resource;

    bool operator==(const RequestKey&) const = default;
  };

  struct RequestKeyHash {
    std::size_t operator()(const RequestKey& key) const noexcept;
  };

  struct PendingRequest {
    RequestKey key;
    std::string execution_resource;
    std::chrono::steady_clock::time_point expires_at;
  };

  struct NormalizedResource {
    std::string authorization;
    std::string execution;
  };

  struct NormalizedRequest {
    RequestKey key;
    std::string execution_resource;
  };

  [[nodiscard]] NormalizedRequest Normalize(const PermissionRequest& request) const;
  [[nodiscard]] NormalizedResource NormalizeResource(PermissionScope scope,
                                                     const std::string& resource,
                                                     bool pattern) const;
  [[nodiscard]] std::optional<PermissionDecision> MatchRule(
      const RequestKey& request) const;
  [[nodiscard]] static RequestKey SessionKey(RequestKey key);
  void PurgeExpired(std::chrono::steady_clock::time_point now);
  void MarkCompleted(const std::string& invocation_id);
  void TouchCompleted(const std::string& invocation_id);

  static constexpr std::size_t kMaxPendingRequests = 1024;
  static constexpr std::size_t kMaxCompletedInvocations = 4096;
  static constexpr auto kPendingTimeout = std::chrono::minutes(5);

  std::filesystem::path project_root_;
  std::string project_root_string_;
  mutable std::mutex mutex_;
  std::vector<PermissionRule> rules_;
  std::unordered_set<RequestKey, RequestKeyHash> allow_session_;
  std::unordered_set<RequestKey, RequestKeyHash> deny_session_;
  std::unordered_map<std::string, PendingRequest> pending_;
  std::unordered_set<std::string> completed_invocations_;
  std::deque<std::string> completed_order_;
};

}  // namespace harness
